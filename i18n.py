_current = DEFAULT_LANG


def _settings_path():
    base = os.environ.get("LOCALAPPDATA", os.path.expanduser("~"))
    d = os.path.join(base, "PDFToolBox")
    os.makedirs(d, exist_ok=True)
    return os.path.join(d, "settings.json")


def load_lang():
    """读取上次选择的语言"""
    global _current
    try:
        with open(_settings_path(), encoding="utf-8") as f:
            v = json.load(f).get("lang")
        if v in PACKS:
            _current = v
    except Exception:
        pass
    return _current


def save_lang(code):
    global _current
    if code not in PACKS:
        return
    _current = code
    try:
        p = _settings_path()
        data = {}
        try:
            with open(p, encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            data = {}
        data["lang"] = code
        with open(p, "w", encoding="utf-8") as f:
            json.dump(data, f)
    except Exception:
        pass


def t(key, **kw):
    """取当前语言的文案，缺词回落中文，再回落 key 本身"""
    s = PACKS.get(_current, {}).get(key)
    if s is None:
        s = PACKS[DEFAULT_LANG].get(key, key)
    if kw:
        try:
            s = s.format(**kw)
        except Exception:
            pass
    return s


def current():
    return _current


